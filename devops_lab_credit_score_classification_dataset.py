"""# adding new columns

"""

# Convert required columns to numeric
numeric_cols = [
    "Annual_Income",
    "Outstanding_Debt",
    "Num_Bank_Accounts",
    "Num_Credit_Card",
    "Total_EMI_per_month",
    "Amount_invested_monthly",
    "Num_of_Delayed_Payment",
    "Num_of_Loan",
    "Num_Credit_Inquiries",
    "Credit_Utilization_Ratio",
    "Interest_Rate"
]

for col in numeric_cols:
    df[col] = pd.to_numeric(
        df[col].astype(str).str.replace("_", "", regex=False),
        errors="coerce"
    )


# 1. Monthly Income
df["Monthly_Income_Calc"] = df["Annual_Income"] / 12


# 2. Debt-to-Income Ratio
df["Debt_to_Income_Ratio"] = (
    df["Outstanding_Debt"] / (df["Annual_Income"] + 1)
)


# 3. Debt per Bank Account
df["Debt_per_Bank_Account"] = (
    df["Outstanding_Debt"] / (df["Num_Bank_Accounts"] + 1)
)


# 4. Debt per Credit Card
df["Debt_per_Credit_Card"] = (
    df["Outstanding_Debt"] / (df["Num_Credit_Card"] + 1)
)


# 5. Credit Card to Bank Account Ratio
df["Credit_to_Bank_Ratio"] = (
    df["Num_Credit_Card"] / (df["Num_Bank_Accounts"] + 1)
)


# 6. EMI to Income Ratio
df["EMI_to_Income_Ratio"] = (
    df["Total_EMI_per_month"] / (df["Monthly_Income_Calc"] + 1)
)


# 7. Investment to Income Ratio
df["Investment_to_Income_Ratio"] = (
    df["Amount_invested_monthly"] / (df["Monthly_Income_Calc"] + 1)
)


# 8. Delayed Payment Ratio
df["Delayed_Payment_Ratio"] = (
    df["Num_of_Delayed_Payment"] / (df["Num_of_Loan"] + 1)
)


# 9. Credit Inquiry per Credit Card
df["Inquiry_per_Credit_Card"] = (
    df["Num_Credit_Inquiries"] / (df["Num_Credit_Card"] + 1)
)


# 10. Total Financial Burden
df["Total_Financial_Burden"] = (
    df["Outstanding_Debt"]
    + df["Total_EMI_per_month"]
    + df["Amount_invested_monthly"]
)


