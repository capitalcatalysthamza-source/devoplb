# model 2 --> logistic regression

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline

numeric_pipeline = Pipeline([
    ('imputer', SimpleImputer(strategy='median')),
    ('scaler', StandardScaler())
])

categorical_pipeline = Pipeline([
    ('imputer', SimpleImputer(strategy='most_frequent')),
    ('encoder', OneHotEncoder(handle_unknown='ignore'))
])

preprocessor = ColumnTransformer([
    ('num', numeric_pipeline, numeric_cols),
    ('cat', categorical_pipeline, categorical_cols)
])

X_train_lr = preprocessor.fit_transform(X_train)
X_test_lr = preprocessor.transform(X_test)

print("Training shape:", X_train_lr.shape)
print("Testing shape:", X_test_lr.shape)

from sklearn.linear_model import LogisticRegression

lr_model = LogisticRegression(
    max_iter=1000,
    random_state=42
)

lr_model.fit(X_train_lr, y_train)

y_pred_lr = lr_model.predict(X_test_lr)
y_prob_lr = lr_model.predict_proba(X_test_lr)



"""# model evaluation accuracy, precision,Recall and f1"""

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score
)

def evaluate_model(name, y_test, y_pred):
    print("\n", "="*40)
    print(name)
    print("="*40)

    print("Accuracy :", accuracy_score(y_test, y_pred))
    print("Precision:", precision_score(
        y_test, y_pred, average='weighted'
    ))
    print("Recall   :", recall_score(
        y_test, y_pred, average='weighted'
    ))
    print("F1 Score :", f1_score(
        y_test, y_pred, average='weighted'
    ))

evaluate_model(
    "CatBoost",
    y_test,
    y_pred_cat
)

evaluate_model(
    "Logistic Regression",
    y_test,
    y_pred_lr
)

